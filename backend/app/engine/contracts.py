class HistoricalDataSource:
    """Historical bar replay data source ensuring zero forward lookahead."""

    def __init__(self, bars: list[BarRecord]) -> None:
        # Group and sort bars chronologically per security
        self._bars = sorted(bars, key=lambda b: b.timestamp)
        self._pointers: dict[str, int] = {}
        self._bars_by_sec: dict[str, list[BarRecord]] = {}
        for b in self._bars:
            self._bars_by_sec.setdefault(b.security_id, []).append(b)
            self._pointers[b.security_id] = 0

    def advance(self, now: datetime) -> list[BarRecord]:
        """Emit bars with timestamp == now."""
        current_bars: list[BarRecord] = []
        for sec_id, sec_bars in self._bars_by_sec.items():
            ptr = self._pointers[sec_id]
            while ptr < len(sec_bars) and sec_bars[ptr].timestamp <= now:
                if sec_bars[ptr].timestamp == now:
                    current_bars.append(sec_bars[ptr])
                ptr += 1
            self._pointers[sec_id] = ptr
        return current_bars

    def get_history(self, security_id: str, until: datetime, count: int) -> list[BarRecord]:
        """Get past `count` bars up to and including `until` without lookahead."""
        sec_bars = self._bars_by_sec.get(security_id, [])
        eligible = [b for b in sec_bars if b.timestamp <= until]
        return eligible[-count:] if count > 0 else eligible

    def get_state(self) -> dict[str, Any]:
        """Serialize data source playback position."""
        return {"pointers": dict(self._pointers)}

    def restore_state(self, state: dict[str, Any]) -> None:
        """Restore playback pointers."""
        self._pointers = dict(state["pointers"])


