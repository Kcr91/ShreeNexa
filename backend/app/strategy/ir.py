# --- Rules and Actions ---


class EntryRule(BaseModel):
    """Trade entry rule specification."""

    model_config = ConfigDict(extra="ignore")

    id: str = Field(min_length=1, description="Unique entry identifier")
    side: OrderSide | Literal["BUY", "SELL"] = Field(
        default=OrderSide.BUY, description="Trade side"
    )
    when: SignalNode = Field(description="Signal tree condition that triggers entry")


class ExitRule(BaseModel):
    """Trade exit and stop-loss / take-profit rule."""

    model_config = ConfigDict(extra="ignore")

    id: str = Field(min_length=1, description="Unique exit identifier")
    type: Literal["target", "stop", "time", "signal", "trailing_stop"] = Field(
        description="Exit category"
    )
    pct: float | None = Field(default=None, gt=0.0, description="Percentage threshold")
    at: str | None = Field(default=None, description="Time of day exit (e.g. 15:15)")
    when: SignalNode | None = Field(default=None, description="Signal condition for signal exit")
    trailing_pct: float | None = Field(default=None, gt=0.0, description="Trailing stop percentage")


class SizingRule(BaseModel):
    """Position sizing policy."""

    model_config = ConfigDict(extra="ignore")

    type: Literal[
        "fixed_qty", "fixed_value", "pct_capital", "risk_pct", "lots", "kelly_fraction"
    ] = "pct_capital"
    qty: int | None = Field(default=None, gt=0, description="Fixed share quantity")
    value: float | None = Field(default=None, gt=0.0, description="Fixed currency value")
    pct: float | None = Field(default=100.0, gt=0.0, le=100.0, description="Percent of capital")
    risk_pct: float | None = Field(
        default=None, gt=0.0, le=100.0, description="Risk budget percentage"
    )
    stop_ref: str | None = Field(default=None, description="Stop exit rule ID used for risk sizing")
    lots: int | None = Field(default=None, gt=0, description="Derivatives lot count")
    cap: float | None = Field(default=None, gt=0.0, description="Maximum fraction cap for Kelly")


class RiskRule(BaseModel):
    """Strategy-level risk parameters and trade limits."""

    model_config = ConfigDict(extra="ignore")

    max_positions: int = Field(default=5, ge=1, description="Maximum concurrent open positions")
    max_daily_loss_pct: float | None = Field(
        default=None, gt=0.0, description="Maximum daily drawdown percentage"
    )
    max_daily_loss_abs: float | None = Field(
        default=None, gt=0.0, description="Maximum daily loss in currency units"
    )
    max_position_value_pct: float | None = Field(
        default=None, gt=0.0, le=100.0, description="Maximum capital allocated per position"
    )
    no_trade_windows: list[str] = Field(
        default_factory=list, description="Restricted time windows (e.g. ['09:15-09:20'])"
    )
    max_trades_per_day: int | None = Field(
        default=None, ge=1, description="Maximum allowed orders per trading day"
    )


# --- Top-Level StrategyIR ---


class StrategyIR(BaseModel):
    """Versioned Strategy Intermediate Representation (IR).

    The single canonical specification shared across screener, backtester,
    paper trading, live execution, and AI generation.
    """

    model_config = ConfigDict(extra="ignore", populate_by_name=True)

    ir_version: int = Field(default=1, ge=1, description="IR schema specification version")
    name: str = Field(min_length=1, description="Strategy name")
    kind: StrategyKind = Field(description="Trading domain kind (stock, option, etc.)")
    horizon: StrategyHorizon = Field(
        description="Time horizon selecting the grading band profile (§10.4.3)"
    )
    strategy_type: StrategyType = Field(
        description="Market archetype selecting the win-rate benchmark band (§10.4.4)"
    )
    universe: UniverseSelector = Field(description="Instrument universe selector")
    timeframe: str = Field(default="5m", description="Base operational timeframe (e.g. 1m, 5m, 1d)")
    session: SessionConfig = Field(
        default_factory=SessionConfig, description="Calendar and session boundaries"
    )
    indicators: dict[str, IndicatorDef] = Field(
        default_factory=dict, description="Declared technical indicators"
    )
    entries: list[EntryRule] = Field(
        default_factory=list, description="Trade entry rule conditions"
    )
    exits: list[ExitRule] = Field(default_factory=list, description="Exit and stop rules")
    sizing: SizingRule = Field(default_factory=SizingRule, description="Position sizing model")
    risk: RiskRule = Field(default_factory=RiskRule, description="Strategy risk thresholds")

    def to_dict(self) -> dict[str, Any]:
        """Serialize model to clean dictionary representation."""
        return self.model_dump(by_alias=True, exclude_none=True)

    def to_json(self, indent: int = 2) -> str:
        """Serialize model to formatted JSON string."""
        return json.dumps(self.to_dict(), indent=indent)

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> StrategyIR:
        """Parse StrategyIR from raw dictionary."""
        return cls.model_validate(data)

    @classmethod
    def from_json(cls, json_str: str) -> StrategyIR:
        """Parse StrategyIR from JSON string."""
        return cls.model_validate_json(json_str)


def export_strategy_ir_json_schema() -> dict[str, Any]:
    """Export complete JSON Schema for the StrategyIR model."""
    return StrategyIR.model_json_schema()
