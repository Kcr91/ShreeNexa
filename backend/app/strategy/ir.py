"""Versioned Pydantic StrategyIR (Intermediate Representation) specification."""

from __future__ import annotations

import json
from enum import StrEnum
from typing import Annotated, Any, Literal

from pydantic import BaseModel, ConfigDict, Field


class StrategyKind(StrEnum):
    """Execution category of the strategy."""

    STOCK = "stock"
    OPTION = "option"
    INVESTING = "investing"
    COMPOSITE = "composite"


class StrategyHorizon(StrEnum):
    """Trading time horizon used to select the grading band profile (§10.4.3)."""

    INTRADAY = "intraday"
    SWING = "swing"
    POSITIONAL = "positional"
    INVESTING = "investing"


class StrategyType(StrEnum):
    """Market style used to select the win-rate benchmark band (§10.4.4)."""

    TREND_FOLLOWING = "trend_following"
    SWING_TRADING = "swing_trading"
    MEAN_REVERSION = "mean_reversion"
    OPTION_SELLING = "option_selling"
    OTHER = "other"


class OrderSide(StrEnum):
    """Order trade side direction."""

    BUY = "BUY"
    SELL = "SELL"


class OptionType(StrEnum):
    """Derivative call / put option contract type."""

    CE = "CE"
    PE = "PE"


class CompareOp(StrEnum):
    """Relational comparison operators for signal conditions."""

    GT = ">"
    LT = "<"
    GTE = ">="
    LTE = "<="
    EQ = "=="
    NEQ = "!="


class InstrumentRef(BaseModel):
    """Reference to an exchange tradable instrument."""

    model_config = ConfigDict(extra="ignore")

    segment: str = Field(description="Exchange segment, e.g., NSE_EQ, NSE_FNO, IDX_I")
    security_id: str = Field(description="Security identifier or symbol code")
    symbol: str | None = Field(default=None, description="Human readable ticker symbol")


# --- Strike selectors ---


class ATMStrike(BaseModel):
    """At-the-money strike offset selector."""

    type: Literal["atm"] = "atm"
    offset: int = Field(default=0, description="Strike offset from ATM (e.g. 0, +1, -1)")


class DeltaStrike(BaseModel):
    """Delta-targeted strike selector."""

    type: Literal["delta"] = "delta"
    target: float = Field(ge=0.0, le=1.0, description="Target absolute delta (0.0 to 1.0)")


class PremiumStrike(BaseModel):
    """Target option premium price selector."""

    type: Literal["premium"] = "premium"
    target: float = Field(gt=0.0, description="Target premium value in currency units")


class AbsoluteStrike(BaseModel):
    """Fixed absolute strike price."""

    type: Literal["absolute"] = "absolute"
    strike: float = Field(gt=0.0, description="Exact strike price")


StrikeSelector = Annotated[
    ATMStrike | DeltaStrike | PremiumStrike | AbsoluteStrike,
    Field(discriminator="type"),
]


class ExpiryRule(BaseModel):
    """Option expiry selection specification."""

    model_config = ConfigDict(extra="ignore")

    type: Literal["weekly", "monthly", "exact"] = "weekly"
    offset: int = Field(default=0, ge=0, description="0 = nearest expiry, 1 = next")
    date: str | None = Field(default=None, description="Exact YYYY-MM-DD for exact expiry")


class OptionLegDef(BaseModel):
    """Definition of an individual option leg within a multi-leg structure."""

    model_config = ConfigDict(extra="ignore")

    id: str = Field(min_length=1, description="Unique leg identifier (e.g., ce, pe, leg1)")
    option_type: OptionType | Literal["CE", "PE"] = Field(description="Call (CE) or Put (PE)")
    strike: StrikeSelector = Field(description="Strike price selection rule")
    side: OrderSide | Literal["BUY", "SELL"] = Field(description="Trade side")
    lots: int = Field(default=1, gt=0, description="Number of standard contract lots")


# --- Universe Selectors ---


class StaticUniverse(BaseModel):
    """Fixed list of pre-selected instruments."""

    type: Literal["static"] = "static"
    instruments: list[InstrumentRef] = Field(min_length=1, description="Explicit instrument list")


class WatchlistUniverse(BaseModel):
    """Dynamic universe sourced from a saved user watchlist."""

    type: Literal["watchlist"] = "watchlist"
    watchlist_id: int = Field(gt=0, description="Database ID of the watchlist")


class ScreenerUniverse(BaseModel):
    """Dynamic universe generated by scheduled screener executions."""

    type: Literal["screener"] = "screener"
    screener_id: int = Field(gt=0, description="Database ID of the screener definition")
    refresh: Literal["daily", "hourly", "every_bar"] = Field(
        default="daily", description="Membership refresh frequency"
    )


class IndexUniverse(BaseModel):
    """Point-in-time constituent universe for a major index (e.g. NIFTY 50)."""

    type: Literal["index"] = "index"
    index_name: str = Field(min_length=1, description="Official index name")


class OptionLegsUniverse(BaseModel):
    """Multi-leg option strategy universe derived from an underlying asset."""

    type: Literal["option_legs"] = "option_legs"
    underlying: InstrumentRef = Field(description="Underlying equity or index reference")
    expiry_rule: ExpiryRule = Field(
        default_factory=ExpiryRule, description="Expiry determination policy"
    )
    legs: list[OptionLegDef] = Field(min_length=1, description="Option legs composing strategy")


UniverseSelector = Annotated[
    StaticUniverse | WatchlistUniverse | ScreenerUniverse | IndexUniverse | OptionLegsUniverse,
    Field(discriminator="type"),
]


class SessionConfig(BaseModel):
    """Trading session and calendar boundaries."""

    model_config = ConfigDict(extra="ignore")

    segment: str = Field(default="NSE_EQ", description="Market segment calendar identifier")
    timezone: str = Field(default="Asia/Kolkata", description="IANA Timezone name")


class IndicatorDef(BaseModel):
    """Declaration of a technical indicator primitive or formula node."""

    model_config = ConfigDict(extra="ignore")

    fn: str = Field(description="Indicator primitive name (e.g. RSI, EMA) or 'custom'")
    params: dict[str, Any] = Field(
        default_factory=dict, description="Parameter dictionary passed to indicator"
    )
    source: str | None = Field(default="close", description="Input price column series")
    indicator_def_id: int | None = Field(
        default=None, description="Reference to custom indicator_def ID"
    )


# --- Signal Grammar and Operands ---


class FieldOperand(BaseModel):
    """Reference to standard price/volume bar field."""

    field: str = Field(description="Column name e.g., open, high, low, close, volume, oi")


class RefOperand(BaseModel):
    """Reference to declared indicator instance."""

    ref: str = Field(description="Indicator instance identifier key")


class ConstOperand(BaseModel):
    """Constant scalar literal operand."""

    const: float | int | bool | str = Field(description="Scalar literal value")


OperandRef = (
    FieldOperand | RefOperand | ConstOperand | dict[str, Any] | float | int | str
)


class LevelRef(BaseModel):
    """Price level anchor reference."""

    model_config = ConfigDict(extra="ignore")

    ref: str | None = Field(default=None, description="Named indicator or level ref")
    type: str | None = Field(default=None, description="prior_high, prev_day_high, orh, etc.")
    minutes: int | None = Field(default=None, description="Opening range minutes duration")
    bars: int | None = Field(default=None, description="Prior N bars lookback")


# --- Signal Nodes (Recursive AST) ---


class AndNode(BaseModel):
    """Boolean AND conjunction node."""

    node: Literal["And"] = "And"
    children: list[SignalNode] = Field(min_length=1)


class OrNode(BaseModel):
    """Boolean OR disjunction node."""

    node: Literal["Or"] = "Or"
    children: list[SignalNode] = Field(min_length=1)


class NotNode(BaseModel):
    """Boolean NOT negation node."""

    node: Literal["Not"] = "Not"
    child: SignalNode


class PriceLevelBreakNode(BaseModel):
    """Breakout of a key price level optionally gated by a preceding condition."""

    model_config = ConfigDict(extra="ignore")

    node: Literal["PriceLevelBreak"] = "PriceLevelBreak"
    level: LevelRef | str | dict[str, Any] = Field(description="Reference level descriptor")
    direction: Literal["above", "below"] = Field(default="above", description="Breakout direction")
    after: SignalNode | None = Field(
        default=None, description="Gating condition that must hold prior to the break"
    )


class SequenceNode(BaseModel):
    """Ordered multi-step condition sequence within a maximum bar window."""

    node: Literal["Sequence"] = "Sequence"
    steps: list[SignalNode] = Field(min_length=2, description="Ordered condition steps")
    within: int = Field(gt=0, description="Max bar duration for the sequence to complete")


class TimeWindowNode(BaseModel):
    """Time-based execution gating condition."""

    model_config = ConfigDict(extra="ignore", populate_by_name=True)

    node: Literal["TimeWindow"] = "TimeWindow"
    mode: Literal["clock", "from_open", "to_close", "dte"] = Field(
        default="clock", description="Time window comparison mode"
    )
    from_time: str | None = Field(
        default=None, alias="from", description="Window start (HH:MM or minutes)"
    )
    to_time: str | None = Field(
        default=None, alias="to", description="Window end (HH:MM or minutes)"
    )
    dte: int | None = Field(default=None, description="Days to expiry filter")


class IndicatorCompareNode(BaseModel):
    """Relational comparison between two operands."""

    model_config = ConfigDict(extra="ignore")

    node: Literal["IndicatorCompare"] = "IndicatorCompare"
    left: OperandRef
    op: CompareOp | str = Field(description="Relational comparison operator")
    right: OperandRef


class CrossOverNode(BaseModel):
    """Strict upward crossover (left crosses above right on the current bar)."""

    model_config = ConfigDict(extra="ignore")

    node: Literal["CrossOver"] = "CrossOver"
    left: OperandRef
    right: OperandRef


class CrossUnderNode(BaseModel):
    """Strict downward crossunder (left crosses below right on the current bar)."""

    model_config = ConfigDict(extra="ignore")

    node: Literal["CrossUnder"] = "CrossUnder"
    left: OperandRef
    right: OperandRef


class PctChangeNode(BaseModel):
    """Percentage rate of change comparison over N bars."""

    model_config = ConfigDict(extra="ignore")

    node: Literal["PctChange"] = "PctChange"
    source: str = Field(default="close", description="Price series name")
    lookback: int = Field(gt=0, description="Lookback bars")
    op: CompareOp | str = Field(description="Relational comparison operator")
    value: float = Field(description="Target percentage move threshold")


class PersistNode(BaseModel):
    """Condition that must evaluate to True for N consecutive bars."""

    node: Literal["Persist"] = "Persist"
    child: SignalNode
    bars: int = Field(gt=0, description="Consecutive bar count")


class StrategySignalNode(BaseModel):
    """Signal composition referencing another strategy's signal."""

    model_config = ConfigDict(extra="ignore")

    node: Literal["StrategySignal"] = "StrategySignal"
    strategy_id: int | str = Field(description="Referenced strategy ID or name")
    signal: str = Field(default="entry", description="Signal identifier (e.g. entry, exit)")


class RegimeNode(BaseModel):
    """Market regime filter condition."""

    model_config = ConfigDict(extra="ignore")

    node: Literal["Regime"] = "Regime"
    detector: str = Field(description="Regime detector model identifier")
    state: str = Field(description="Required regime state label (e.g. trending_up, volatile)")


class CustomPythonNode(BaseModel):
    """Sandboxed custom Python calculation escape hatch."""

    model_config = ConfigDict(extra="ignore")

    node: Literal["CustomPython"] = "CustomPython"
    ref: str = Field(description="Custom python module or code reference")


SignalNode = Annotated[
    AndNode
    | OrNode
    | NotNode
    | PriceLevelBreakNode
    | SequenceNode
    | TimeWindowNode
    | IndicatorCompareNode
    | CrossOverNode
    | CrossUnderNode
    | PctChangeNode
    | PersistNode
    | StrategySignalNode
    | RegimeNode
    | CustomPythonNode,
    Field(discriminator="node"),
]

